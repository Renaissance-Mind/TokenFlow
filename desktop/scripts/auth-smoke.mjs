import { _electron as electron, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import electronPath from 'electron';

const helper = process.env.TOKENFLOW_AUTH_TEST_SERVER;
if (!helper) throw new Error('Set TOKENFLOW_AUTH_TEST_SERVER to TokenFlow_Server/scripts/desktop-test-server.mjs');
const { withDesktopTestServer } = await import(pathToFileURL(path.resolve(helper)).href);
const desktop = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
await withDesktopTestServer(async ({url,approve,request,db}) => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(),'tokenflow-desktop-auth-'));
  const env = { ...process.env,TOKENFLOW_HOME:path.join(temp,'collector'),TOKENFLOW_DESKTOP_DATA:path.join(temp,'app'),TOKENFLOW_SCAN_HOME:path.join(temp,'sources'),TOKENFLOW_SERVER_URL:url };
  delete env.ELECTRON_RUN_AS_NODE;
  await fs.mkdir(env.TOKENFLOW_SCAN_HOME,{recursive:true});
  let instance = await electron.launch({args:[desktop],env,timeout:60_000});
  try {
    let local = await instance.firstWindow();
    await local.waitForURL(/\/renderer\/index.html(?:\?|$)/);
    await local.waitForLoadState('domcontentloaded');
    await expect.poll(async () => { const value = await local.evaluate(() => window.tokenflow.getState()); return !!value.summary && !value.busy; },{timeout:60_000}).toBe(true);
    await local.evaluate(() => window.tokenflow.login('google'));
    await expect.poll(async () => !!(await local.evaluate(() => window.tokenflow.getState())).login).toBe(true);
    const code = (await local.evaluate(() => window.tokenflow.getState())).login.code;
    assert.equal((await approve(code)).status,200);
    await expect.poll(async () => { const value = await local.evaluate(() => window.tokenflow.getState()); return value.hasDashboard && !value.busy; },{timeout:60_000}).toBe(true);
    let state = await local.evaluate(() => window.tokenflow.getState());
    if (!state.account) console.log('Unexpected account state:', {hasDashboard:state.hasDashboard,busy:state.busy,error:state.error,notice:state.notice});
    assert.equal(state.account.name,'Desktop acceptance');
    assert.equal(state.hasCollector,true);
    const config = JSON.parse(await fs.readFile(path.join(env.TOKENFLOW_HOME,'config.json'),'utf8'));
    assert.equal((await request('/api/device/status',undefined,config.deviceToken)).status,200);
    assert.ok(config.lastSyncAt);
    const encrypted = await fs.readFile(path.join(env.TOKENFLOW_DESKTOP_DATA,'desktop-auth.bin'));
    assert.ok(!encrypted.toString().includes('tu_desktop_'));
    const dashboard = instance.windows().find((page) => page.url().includes('/dashboard'));
    assert.ok(dashboard);
    assert.equal(await dashboard.evaluate(() => typeof window.tokenflow),'undefined');
    await dashboard.waitForFunction(() => !document.getElementById('app').classList.contains('hidden'),null,{timeout:60_000});
    await dashboard.screenshot({path:path.join(desktop,'test-results','desktop-dashboard.png'),fullPage:true});
    await local.evaluate(() => window.tokenflow.saveSettings({paused:true}));
    await local.evaluate(() => window.tokenflow.sync());
    state = await local.evaluate(() => window.tokenflow.getState());
    assert.equal(state.settings.paused,true); assert.equal(state.error,null);
    await instance.close();
    await promisify(execFile)(electronPath,[desktop,'--collector-sync'],{env,timeout:60_000});
    const afterHeadless = JSON.parse(await fs.readFile(path.join(env.TOKENFLOW_HOME,'config.json'),'utf8'));
    assert.ok(Date.parse(afterHeadless.lastSyncAt) >= Date.parse(config.lastSyncAt));
    const authFile = path.join(env.TOKENFLOW_DESKTOP_DATA,'desktop-auth.bin');
    const pendingFile = path.join(env.TOKENFLOW_DESKTOP_DATA,'desktop-auth.pending.bin');
    await fs.rename(authFile,pendingFile);
    instance = await electron.launch({args:[desktop],env,timeout:60_000});
    local = await instance.firstWindow();
    await local.waitForURL(/\/renderer\/index.html(?:\?|$)/);
    await expect.poll(async () => { const value = await local.evaluate(() => window.tokenflow.getState()); return value.hasDashboard && !value.busy; },{timeout:60_000}).toBe(true);
    state = await local.evaluate(() => window.tokenflow.getState());
    assert.equal(state.account.name,'Desktop acceptance'); assert.equal(state.settings.paused,true);
    assert.ok((await fs.stat(authFile)).isFile());
    await assert.rejects(fs.stat(pendingFile),{code:'ENOENT'});
    assert.equal((await db.prepare('SELECT COUNT(*) AS count FROM desktop_credentials WHERE revoked_at IS NULL').first()).count,1);
    await local.evaluate(() => window.tokenflow.logout());
    assert.equal((await local.evaluate(() => window.tokenflow.getState())).hasDashboard,false);
    assert.equal((await db.prepare('SELECT COUNT(*) AS count FROM desktop_credentials WHERE revoked_at IS NULL').first()).count,0);
    assert.equal((await fs.readFile(path.join(env.TOKENFLOW_HOME,'config.json'),'utf8')).includes('tu_dev_'),false);
    assert.equal((await request('/api/device/status',undefined,config.deviceToken)).status,401);
    console.log('Desktop login smoke passed against real Worker/D1: one authorization, encrypted persistence, authenticated dashboard, collector sync, manual sync while paused, restart/journal recovery, and logout. Provider identity is a test-account fixture.');
  } finally { await instance.close(); await fs.rm(temp,{recursive:true,force:true}); }
});

import {_electron as electron,expect} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {pathToFileURL,fileURLToPath} from 'node:url';
const helper=process.env.TOKENFLOW_AUTH_TEST_SERVER;
if(!helper)throw new Error('Set TOKENFLOW_AUTH_TEST_SERVER to desktop-test-server.mjs');
const {withDesktopTestServer}=await import(pathToFileURL(path.resolve(helper)).href);
const desktop=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
await withDesktopTestServer(async({url,request,db,userId,sessionToken})=>{
  const temp=await fs.mkdtemp(path.join(os.tmpdir(),'tokenflow-settings-design-'));
  const env={...process.env,TOKENFLOW_HOME:path.join(temp,'collector'),TOKENFLOW_DESKTOP_DATA:path.join(temp,'app'),TOKENFLOW_SCAN_HOME:path.join(temp,'sources'),TOKENFLOW_SERVER_URL:url,TOKENFLOW_NODE_PATH:process.execPath};
  delete env.ELECTRON_RUN_AS_NODE;delete env.TOKENFLOW_CLI_PATH;
  for(const key of Object.keys(env))if(/^(CODEX_HOME|CLAUDE_HOME|GEMINI_HOME|GEMINI_DATA_DIR|OPENCODE_HOME|OPENCODE_DB|KIMI_DATA_DIR|QWEN_DATA_DIR|AMP_DATA_DIR|CODEBUFF_DATA_DIR|DROID_SESSIONS_DIR|GOOSE_PATH_ROOT|HERMES_HOME|KILO_DATA_DIR|OPENCLAW_DIR|PI_AGENT_DIR|DSH_DATA_DIR|GROK_HOME|ZCODE_HOME|COPILOT_HOME|COPILOT_OTEL_FILE_EXPORTER_PATH|ANTIGRAVITY_DATA_DIR|TOKENUSAGE_SERVER_URL|TOKENUSAGE_HOME)$/.test(key))delete env[key];
  await fs.mkdir(env.TOKENFLOW_HOME,{recursive:true});await fs.mkdir(env.TOKENFLOW_SCAN_HOME,{recursive:true});
  await db.prepare('UPDATE users SET email=?1 WHERE id=?2').bind('alex@example.test',userId).run();
  const flow=await(await request('/api/device/start',{device_name:'My MacBook',platform:process.platform})).json();
  assert.equal((await request('/api/device/approve',{user_code:flow.user_code},undefined,{Cookie:'tu_session='+sessionToken,Origin:url})).status,200);
  const linked=await(await request('/api/device/poll',{device_code:flow.device_code})).json();
  await fs.writeFile(path.join(env.TOKENFLOW_HOME,'config.json'),JSON.stringify({serverUrl:url,deviceName:'My MacBook',deviceId:linked.device_id,deviceToken:linked.token}));
  const instance=await electron.launch({args:[desktop],env,timeout:60_000});
  try{
    const dashboard=await instance.firstWindow();await dashboard.waitForURL(/mode=dashboard$/);
    await expect.poll(async()=>{const s=await dashboard.evaluate(()=>window.tokenflow.getState());if(s.error)throw new Error(s.error);return !!s.summary&&!s.busy;},{timeout:60_000}).toBe(true);
    await dashboard.evaluate(()=>{window.retainedDashboard=document.getElementById('app');});
    const before=await instance.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().map(w=>({id:w.id,bounds:w.getBounds()})));
    await dashboard.locator('#desktopSettings').click();
    await expect.poll(()=>instance.windows().some(p=>p.url().includes('mode=settings'))).toBe(true);
    const settings=instance.windows().find(p=>p.url().includes('mode=settings'));await settings.waitForLoadState('domcontentloaded');
    await expect.poll(()=>dashboard.evaluate(()=>document.body.inert)).toBe(true);
    const errors=[];settings.on('pageerror',e=>errors.push(e.message));
    await settings.locator('[data-section=authentication]').click();
    await expect(settings.locator('#accountDetails')).toHaveText('alex@example.test');
    await settings.setViewportSize({width:1440,height:960});
    await expect(settings.locator('#operationProgress')).toBeHidden();
    await settings.screenshot({path:path.join(desktop,'test-results','settings-light-connected.png')});
    const reading=settings.evaluate(()=>window.tokenflow.scan());
    await expect(settings.locator('#operationProgress')).toBeVisible();
    await expect(settings.locator('#progressTrack')).toHaveAttribute('aria-valuenow', /\d/);
    await settings.screenshot({path:path.join(desktop,'test-results','settings-light-reading.png')});
    await reading;await expect(settings.locator('#operationProgress')).toBeHidden();
    await settings.setViewportSize({width:1440,height:916});
    await settings.locator('[data-section=cliSection]').click();
    assert.equal(await settings.locator('#update').evaluate(el=>el.getBoundingClientRect().bottom<=innerHeight),true);
    await settings.screenshot({path:path.join(desktop,'test-results','settings-light-native-height.png')});
    await settings.locator('[data-section="cliSection"]').click();await expect(settings.locator('#update')).toBeInViewport();
    await settings.setViewportSize({width:760,height:916});
    assert.equal(await settings.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await settings.screenshot({path:path.join(desktop,'test-results','settings-light-compact.png')});
    await settings.locator('#dashboardShortcut').click();
    await expect.poll(()=>dashboard.evaluate(()=>document.body.inert)).toBe(false);
    assert.equal(await dashboard.evaluate(()=>window.retainedDashboard===document.getElementById('app')),true);
    assert.deepEqual(await instance.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().map(w=>({id:w.id,bounds:w.getBounds()}))),before);
    assert.deepEqual(errors,[]);
    console.log('Settings design check passed: one native window, preserved Dashboard, light design, real-operation progress, native height, compact layout, section navigation and no renderer errors.');
  }finally{await instance.close();await fs.rm(temp,{recursive:true,force:true});}
});
